# shellcheck shell=bash
# Shared helper for the macos-*.sh scripts.
#
# Each script registers its settings, then calls run_settings "$@":
#
#   source "$(dirname "${BASH_SOURCE[0]}")/lib/macos-defaults.sh"
#   setting tilesize "Dock icon size: 48 px" com.apple.dock tilesize int 48
#   run_settings "$@"
#   macos_settings_done Dock          # restarts the Dock if anything changed
#
# How a script behaves depends on its arguments:
#   --list         print "id|label" for each setting (install-master.sh uses
#                  this to show every setting as its own checkbox)
#   <id>...        apply exactly these settings, without asking (what
#                  install-master.sh passes for the boxes you ticked)
#   (no args)      run on its own: propose each setting in turn, showing the
#                  current and new value, and apply it only if you answer y
# Settings that already have the new value are left alone either way.
#
# setting <id> <label> <domain> <key> <type> <value> [<domain> <key> <type> <value>]...
#   type: bool | int | float | string
#   A domain written as currentHost:<domain> uses `defaults -currentHost`.
#   All the writes in one setting are applied together.
#
# custom_setting <id> <label> <function>
#   For changes that aren't `defaults` values. The function is called with
#   "is_set" (return 0 if already done), "describe" (print what would change)
#   or "apply".
#
# Before a `defaults` value is changed for the first time, its original value
# is recorded in ~/.mac-install/restore-macos-defaults.sh, so running that
# script puts everything back.
#
# Bash 3.2 compatible (macOS /bin/bash).

MACOS_RESTORE_DIR="${MACOS_RESTORE_DIR:-$HOME/.mac-install}"
MACOS_RESTORE_FILE="$MACOS_RESTORE_DIR/restore-macos-defaults.sh"
_MACOS_CHANGED=0

# Registered settings (parallel arrays). For `defaults` settings, the writes
# live in _S_SPECS, groups of four starting at _S_START for _S_LEN entries.
_S_IDS=()
_S_LABELS=()
_S_FUNCS=()
_S_START=()
_S_LEN=()
_S_SPECS=()

require_macos() {
    if [ "$(uname -s)" != "Darwin" ]; then
        echo "This script changes macOS settings and only runs on macOS." >&2
        exit 1
    fi
}

# ask "<question>" — returns 0 for yes. Defaults to no, including when there is
# no terminal to ask on.
ask() {
    local reply=""
    if ! { read -r -p "$1 [y/N] " reply < /dev/tty; } 2>/dev/null; then
        echo "$1 (no terminal to ask on; leaving unchanged)"
        reply=""
    fi
    case "$reply" in
        [yY] | [yY][eE][sS]) return 0 ;;
        *) return 1 ;;
    esac
}

setting() {
    local id="$1" label="$2"
    shift 2
    if [ "$#" -eq 0 ] || [ $(($# % 4)) -ne 0 ]; then
        echo "setting $id: expected groups of <domain> <key> <type> <value>" >&2
        exit 1
    fi
    _S_IDS+=("$id")
    _S_LABELS+=("$label")
    _S_FUNCS+=("")
    _S_START+=("${#_S_SPECS[@]}")
    _S_LEN+=("$#")
    _S_SPECS+=("$@")
}

custom_setting() {
    _S_IDS+=("$1")
    _S_LABELS+=("$2")
    _S_FUNCS+=("$3")
    _S_START+=(0)
    _S_LEN+=(0)
}

# _defaults <verb> <domain> [args...] — `defaults`, honouring currentHost:<domain>.
_defaults() {
    local verb="$1" domain="$2"
    shift 2
    case "$domain" in
        currentHost:*) defaults -currentHost "$verb" "${domain#currentHost:}" "$@" ;;
        *) defaults "$verb" "$domain" "$@" ;;
    esac
}

# _norm <type> <value> — canonical form for comparing with `defaults read` output.
_norm() {
    case "$1" in
        bool)
            case "$2" in
                1 | true | TRUE | yes | YES) echo 1 ;;
                *) echo 0 ;;
            esac
            ;;
        int | float) awk -v v="$2" 'BEGIN { printf "%g\n", v + 0 }' ;;
        *) printf '%s\n' "$2" ;;
    esac
}

# _show <type> <normalised value> — human-readable value.
_show() {
    if [ "$1" = bool ]; then
        if [ "$2" = 1 ]; then echo true; else echo false; fi
    else
        printf '%s\n' "$2"
    fi
}

# _restore_header — create the restore script if it doesn't exist yet.
_restore_header() {
    [ -f "$MACOS_RESTORE_FILE" ] && return 0
    mkdir -p "$MACOS_RESTORE_DIR"
    cat > "$MACOS_RESTORE_FILE" <<'EOF'
#!/usr/bin/env bash
# Restores macOS settings to the values they had before mac-install changed them.
# Generated by lib/macos-defaults.sh: each setting is recorded the first time it
# is changed, so this always holds the original value.
# Afterward, log out and back in (or restart Finder, Dock and SystemUIServer).
EOF
    chmod +x "$MACOS_RESTORE_FILE"
}

# restore_append <marker> <line>... — record restore lines once per marker.
restore_append() {
    local marker="# setting: $1"
    shift
    _restore_header
    grep -qxF "$marker" "$MACOS_RESTORE_FILE" && return 0
    {
        echo
        echo "$marker"
        printf '%s\n' "$@"
    } >> "$MACOS_RESTORE_FILE"
}

# _record_restore <domain> <key> — record how to put this value back.
_record_restore() {
    local domain="$1" key="$2" d="$1" hostflag="" cur type flag line
    case "$domain" in
        currentHost:*)
            hostflag="-currentHost "
            d="${domain#currentHost:}"
            ;;
    esac
    if cur="$(_defaults read "$domain" "$key" 2>/dev/null)"; then
        type="$(_defaults read-type "$domain" "$key" 2>/dev/null | awk '{ print $NF }')"
        case "$type" in
            boolean)
                flag=-bool
                if [ "$cur" = 1 ]; then cur=true; else cur=false; fi
                ;;
            integer) flag=-int ;;
            float) flag=-float ;;
            string) flag=-string ;;
            *) flag="" ;;
        esac
        if [ -n "$flag" ]; then
            line="$(printf 'defaults %swrite %q %q %s %q' "$hostflag" "$d" "$key" "$flag" "$cur")"
        else
            line="# original value was of type '$type' and is not restored automatically"
        fi
    else
        line="$(printf 'defaults %sdelete %q %q 2>/dev/null || true' "$hostflag" "$d" "$key")"
    fi
    restore_append "$domain $key" "$line"
}

# _pending <index> — set _PENDING to the "domain key: old → new" lines for the
# values in this setting that differ from what it wants (empty if all match).
_pending() {
    local idx="$1" i end domain key type want cur shown
    _PENDING=()
    i="${_S_START[$idx]}"
    end=$((i + ${_S_LEN[$idx]}))
    for (( ; i < end; i += 4)); do
        domain="${_S_SPECS[i]}" key="${_S_SPECS[i + 1]}" type="${_S_SPECS[i + 2]}"
        want="$(_norm "$type" "${_S_SPECS[i + 3]}")"
        if cur="$(_defaults read "$domain" "$key" 2>/dev/null)"; then
            cur="$(_norm "$type" "$cur")"
            [ "$cur" = "$want" ] && continue
            shown="$(_show "$type" "$cur")"
        else
            shown="not set (macOS default)"
        fi
        _PENDING+=("    ${domain#currentHost:} $key: $shown → $(_show "$type" "$want")")
    done
}

# _write <index> — record originals and write every value in this setting.
_write() {
    local idx="$1" i end domain key
    i="${_S_START[$idx]}"
    end=$((i + ${_S_LEN[$idx]}))
    for (( ; i < end; i += 4)); do
        domain="${_S_SPECS[i]}" key="${_S_SPECS[i + 1]}"
        _record_restore "$domain" "$key"
        _defaults write "$domain" "$key" "-${_S_SPECS[i + 2]}" "${_S_SPECS[i + 3]}"
    done
}

# _handle <index> <ask|apply> — check one setting, then ask about it or apply it.
_handle() {
    local idx="$1" mode="$2" label="${_S_LABELS[$1]}" fn="${_S_FUNCS[$1]}"
    if [ -n "$fn" ]; then
        if "$fn" is_set; then
            echo "✓ $label (already set)"
            return 0
        fi
        if [ "$mode" = ask ]; then
            echo
            echo "• $label"
            "$fn" describe
            if ! ask "  Apply?"; then echo "  – skipped"; return 0; fi
        fi
        "$fn" apply
    else
        _pending "$idx"
        if [ "${#_PENDING[@]}" -eq 0 ]; then
            echo "✓ $label (already set)"
            return 0
        fi
        if [ "$mode" = ask ]; then
            echo
            echo "• $label"
            printf '%s\n' "${_PENDING[@]}"
            if ! ask "  Apply?"; then echo "  – skipped"; return 0; fi
        fi
        _write "$idx"
    fi
    _MACOS_CHANGED=1
    if [ "$mode" = ask ]; then echo "  ✓ applied"; else echo "✓ $label"; fi
}

# run_settings "$@" — see the top of this file.
run_settings() {
    local i id found
    if [ "${1:-}" = "--list" ]; then
        for ((i = 0; i < ${#_S_IDS[@]}; i++)); do
            printf '%s|%s\n' "${_S_IDS[i]}" "${_S_LABELS[i]}"
        done
        exit 0
    fi

    require_macos

    if [ "$#" -eq 0 ]; then
        for ((i = 0; i < ${#_S_IDS[@]}; i++)); do
            _handle "$i" ask
        done
        return 0
    fi

    # Check every id first, so a typo doesn't leave a half-applied group.
    for id in "$@"; do
        found=0
        for ((i = 0; i < ${#_S_IDS[@]}; i++)); do
            [ "${_S_IDS[i]}" = "$id" ] && found=1
        done
        if [ "$found" = 0 ]; then
            echo "Unknown setting: $id (run $(basename "$0") --list to see them)" >&2
            exit 1
        fi
    done
    # Apply in the order the script defines them.
    for ((i = 0; i < ${#_S_IDS[@]}; i++)); do
        for id in "$@"; do
            if [ "${_S_IDS[i]}" = "$id" ]; then
                _handle "$i" apply
                break
            fi
        done
    done
}

# macos_settings_done [<app>...] — restart the given apps (Finder, Dock,
# SystemUIServer) so changes show up, but only if something was changed.
# shellcheck disable=SC2120  # the app list is optional
macos_settings_done() {
    local app
    echo
    if [ "$_MACOS_CHANGED" != 1 ]; then
        echo "No changes made."
        return 0
    fi
    for app in "$@"; do
        killall "$app" >/dev/null 2>&1 || true
    done
    [ "$#" -gt 0 ] && echo "Restarted: $*"
    echo "To undo every change made so far: $MACOS_RESTORE_FILE"
}
